/**
 * Генерирует N студентов на основе базовой группы.
 *
 * @param {number} count        — сколько студентов сгенерировать (по умолчанию 50)
 * @param {string} baseGroup    — базовая группа, напр. "ББМО-01-23"
 * @returns {Array}             — массив студентов
 */
function generateStudents(count = 50, baseGroup = 'ББМО-01-23') {
  // Парсим базовую группу: "ББМО-01-23" → { prefix: 'ББМО', year: 23 }
  const match = baseGroup.match(/^([А-ЯA-Z]+)-(\d+)-(\d{2})$/i);
  if (!match) {
    throw new Error(`Неверный формат базовой группы: ${baseGroup}`);
  }
  const [, prefix, , yearStr] = match;
  const year = parseInt(yearStr, 10);

  // Сколько разных групп делать (например, 5: ББМО-01-23 .. ББМО-05-23)
  const GROUPS_COUNT = 5;

  const students = [];

  for (let i = 0; i < count; i++) {
    // Определяем пол случайно (примерно 50/50)
    const isMale = Math.random() < 0.5;

    const firstName = isMale
      ? pick(MALE_FIRST_NAMES)
      : pick(FEMALE_FIRST_NAMES);

    // Фамилия — всегда мужская форма (в русском языке обычно так и хранят)
    const lastName = pick(MALE_LAST_NAMES);

    const name = `${lastName} ${firstName}`;

    // Случайная группа из доступных
    const groupNum = randInt(1, GROUPS_COUNT);
    const group = formatGroup(prefix, groupNum, year);

    // Курс 1..4
    const course = randInt(1, 4);

    students.push({
      id: i + 1,
      name,
      group,
      course,
      gender: isMale ? 'male' : 'female',
      enrollmentYear: 2000 + year,
      graduateYear: 2000 + year + 4,
    });
  }

  return students;
}

